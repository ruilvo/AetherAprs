using AetherAprs.Models.Aprs;
using AetherAprs.Models.Messaging;
using System;

namespace AetherAprs.Data.Entities;

/// <summary>
/// Durable work item for one logical outbound APRS message. The row owns the
/// delivery state, the attempt counter, the expiry instant and the wire number
/// reservation; packet history keeps its own row for display only.
/// </summary>
public sealed class OutboxMessageRecord
{
    /// <summary>Logical message identity, generated by the caller before enqueue.</summary>
    public Guid Id { get; set; }

    /// <summary>Normalized addressee callsign base (uppercase, without SSID).</summary>
    public string AddresseeBase { get; set; } = string.Empty;

    /// <summary>Addressee SSID; part of the normalized peer identity.</summary>
    public AprsSsid AddresseeSsid { get; set; }

    public string Text { get; set; } = string.Empty;

    /// <summary>Reserved APRS wire number; null while the message is queued.</summary>
    public int? MessageNumber { get; set; }

    public MessageDeliveryStatus Status { get; set; }

    /// <summary>Transmission attempts made, including the initial one.</summary>
    public int AttemptCount { get; set; }

    /// <summary>UTC instant the caller created the logical message.</summary>
    public DateTime CreatedAt { get; set; }

    /// <summary>UTC instant after which pending work is no longer replayed.</summary>
    public DateTime ExpiresAt { get; set; }

    /// <summary>UTC instant of the next scheduled attempt; null when not scheduled.</summary>
    public DateTime? NextAttemptAt { get; set; }

    /// <summary>
    /// UTC instant after which the wire number may be reused. Set when the
    /// message reaches a terminal state, so a late ACK cannot hit a reused number.
    /// </summary>
    public DateTime? NumberReleaseAt { get; set; }

    public DateTime UpdatedAt { get; set; }

    /// <summary>Last port used for a transmission attempt.</summary>
    public Guid? PortId { get; set; }
}
